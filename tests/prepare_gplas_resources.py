#!/usr/bin/env python3
"""Rebuild guarded gplas resources from the official fixed source archive."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import tarfile


ROOT = Path(__file__).resolve().parents[1]
ARCHIVE_SHA256 = '4c70b36255d83ee6e243373eafd9dbeb95059a59657bcceb0a35044710578d40'
VERSION_FILE = ("# file generated by setuptools_scm\n"
                "# don't change, don't track in version control\n"
                "__version__ = version = '1.1.1.dev8+g00cf37b'\n"
                "__version_tuple__ = version_tuple = (1, 1, 1, 'dev8', 'g00cf37b')\n")


def prepare(archive, output):
    spec = importlib.util.spec_from_file_location('gplas_checked', ROOT / 'bin/gplas_checked.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    expected = module.SOURCE_SHA256
    data = Path(archive).read_bytes()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA256:
        raise ValueError('Unsupported gplas source archive')
    if hashlib.sha256(VERSION_FILE.encode()).hexdigest() != expected['gplas/version.py']:
        raise ValueError('Generated SCM metadata differs from the verified native build')
    output = Path(output)
    if output.exists():
        raise ValueError('Resource output already exists')
    files = {}
    with tarfile.open(archive) as bundle:
        for member in bundle:
            if not member.isfile():
                continue
            parts = Path(member.name).parts
            if len(parts) < 2:
                raise ValueError('Unexpected archive root')
            relative = str(Path(*parts[1:]))
            if relative not in expected or relative in files:
                raise ValueError('Unexpected or duplicate source member: ' + relative)
            content = bundle.extractfile(member).read()
            if hashlib.sha256(content).hexdigest() != expected[relative]:
                raise ValueError('Source blob checksum mismatch: ' + relative)
            files[relative] = content
    if set(files) != set(expected) - {'gplas/version.py'}:
        raise ValueError('Incomplete source archive')
    files['gplas/version.py'] = VERSION_FILE.encode()
    output.mkdir(parents=True)
    for relative, content in files.items():
        path = output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    metadata = {'source_commit': '00cf37bec5e44b05ee30c8a4c99e987abbbb4c4f',
                'archive_sha256': ARCHIVE_SHA256, 'original_blobs': 45,
                'generated_version_sha256': expected['gplas/version.py'],
                'version_metadata_basis': 'byte-identical to actual upstream setuptools_scm build from Git describe 1.1.0-8-g00cf37b; generated metadata, not a file present in the archive',
                'scope': 'resource reconstruction only; not tool execution or biological validation'}
    (output / 'resource_provenance.json').write_text(json.dumps(metadata, indent=2) + '\n')
    return metadata


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(prepare(args.archive, args.output), indent=2))
